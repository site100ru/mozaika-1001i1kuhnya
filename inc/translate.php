<?php
/**
 * Автоматическая транслитерация ссылок (слагов) на латиницу.
 *
 * Применяется ко всем слагам сайта (записи, страницы, термины таксономий).
 * Кириллический заголовок вида «Кухня на заказ» превращается в slug
 * «kuhnya-na-zakaz» вместо уродливого %d0%ba%d1%83...
 *
 * Подключается из functions.php.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit; // Прямой доступ запрещён.
}

/**
 * Транслитерация кириллицы в латиницу.
 *
 * @param string $string Исходная строка (как правило, заголовок записи/термина).
 * @return string Строка в латинице.
 */
function kuhnya_cyr_to_lat( $string ) {
	$map = [
		'А' => 'A', 'Б' => 'B', 'В' => 'V', 'Г' => 'G', 'Д' => 'D',
		'Е' => 'E', 'Ё' => 'Yo', 'Ж' => 'Zh', 'З' => 'Z', 'И' => 'I',
		'Й' => 'Y', 'К' => 'K', 'Л' => 'L', 'М' => 'M', 'Н' => 'N',
		'О' => 'O', 'П' => 'P', 'Р' => 'R', 'С' => 'S', 'Т' => 'T',
		'У' => 'U', 'Ф' => 'F', 'Х' => 'Kh', 'Ц' => 'Ts', 'Ч' => 'Ch',
		'Ш' => 'Sh', 'Щ' => 'Shch', 'Ъ' => '', 'Ы' => 'Y', 'Ь' => '',
		'Э' => 'E', 'Ю' => 'Yu', 'Я' => 'Ya',
		'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd',
		'е' => 'e', 'ё' => 'yo', 'ж' => 'zh', 'з' => 'z', 'и' => 'i',
		'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n',
		'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't',
		'у' => 'u', 'ф' => 'f', 'х' => 'kh', 'ц' => 'ts', 'ч' => 'ch',
		'ш' => 'sh', 'щ' => 'shch', 'ъ' => '', 'ы' => 'y', 'ь' => '',
		'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
	];

	return strtr( $string, $map );
}

/**
 * Фильтр слага: транслитерируем кириллицу ДО того, как WordPress
 * (sanitize_title_with_dashes на приоритете 10) превратит её в percent-кодировку.
 * Поэтому приоритет 9 — на этом этапе $title ещё содержит кириллицу,
 * а штатная функция ядра потом аккуратно соберёт из латиницы корректный slug.
 *
 * @param string $title     Обрабатываемый заголовок.
 * @param string $raw_title Исходный заголовок (не используется, оставлен для совместимости фильтра).
 * @param string $context   Контекст вызова.
 * @return string
 */
function kuhnya_transliterate_slug( $title, $raw_title = '', $context = 'save' ) {
	if ( preg_match( '/[А-Яа-яЁё]/u', $title ) ) {
		$title = kuhnya_cyr_to_lat( $title );
	}
	return $title;
}
add_filter( 'sanitize_title', 'kuhnya_transliterate_slug', 9, 3 );
